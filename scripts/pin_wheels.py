"""Resolve manifest/requirements.in to exact wheel URLs + SHA-256 (run rarely).

Only official indexes: PyPI's JSON API for normal packages, the PyTorch
cu128 index for torch/torchvision. Writes the "wheels" list of
manifest/sources.json and manifest/requirements.lock (pip --require-hashes
format). Picks the one wheel that runs on CPython 3.11 / 64-bit Windows.

    py -3 scripts/pin_wheels.py
"""
from __future__ import annotations

import html.parser
import json
import re
import sys
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
MANIFEST = REPO / "manifest"
TORCH_INDEX = "https://download.pytorch.org/whl/cu128/{name}/"
# Tags acceptable on cp311 win_amd64, best first.
GOOD_TAGS = ("cp311-cp311-win_amd64", "cp311-abi3-win_amd64", "cp310-abi3-win_amd64",
             "cp39-abi3-win_amd64", "cp38-abi3-win_amd64", "cp37-abi3-win_amd64",
             "py3-none-win_amd64", "py3-none-any", "py2.py3-none-any")


def tag_of(filename: str) -> str:
    parts = filename[:-4].split("-")
    return "-".join(parts[-3:])


def rank(filename: str) -> int:
    t = tag_of(filename)
    for i, good in enumerate(GOOD_TAGS):
        if t == good:
            return i
    # compressed tag sets like "py2.py3-none-any" or "cp37.cp38-abi3-win_amd64"
    py, abi, plat = t.split("-")
    if plat in ("win_amd64", "any") and abi in ("none", "abi3") and any(
            p in ("py3", "cp37", "cp38", "cp39", "cp310", "cp311") for p in py.split(".")):
        return len(GOOD_TAGS)
    return -1


def get(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read()


def pypi_wheel(name: str, version: str) -> dict:
    d = json.loads(get(f"https://pypi.org/pypi/{name}/{version}/json"))
    files = [f for f in d["urls"] if f["packagetype"] == "bdist_wheel" and rank(f["filename"]) >= 0]
    if not files:
        raise SystemExit(f"no cp311 win_amd64 wheel on PyPI for {name}=={version}")
    f = min(files, key=lambda f: rank(f["filename"]))
    return {"name": name, "version": version, "file": f["filename"], "url": f["url"],
            "sha256": f["digests"]["sha256"], "size": f["size"], "index": "pypi"}


class _Links(html.parser.HTMLParser):
    def __init__(self):
        super().__init__()
        self.links = []

    def handle_starttag(self, tag, attrs):
        if tag == "a":
            self.links.append(dict(attrs).get("href", ""))


def torch_wheel(name: str, version: str) -> dict:
    page = get(TORCH_INDEX.format(name=name)).decode()
    p = _Links()
    p.feed(page)
    want = f"{name}-{version.replace('+', '%2B')}-cp311-cp311-win_amd64.whl"
    for href in p.links:
        path, _, frag = href.partition("#sha256=")
        if path.rsplit("/", 1)[-1] == want and frag:
            url = path if path.startswith("http") else "https://download.pytorch.org" + path
            return {"name": name, "version": version, "file": want.replace("%2B", "+"), "url": url,
                    "sha256": frag, "size": None, "index": "download.pytorch.org/whl/cu128"}
    raise SystemExit(f"{want} not found on the PyTorch cu128 index")


def main():
    reqs = []
    for line in (MANIFEST / "requirements.in").read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            n, v = line.split("==")
            reqs.append((n, v))
    wheels = []
    for n, v in reqs:
        w = torch_wheel(n, v) if "+cu" in v else pypi_wheel(n, v)
        print(f"{w['file']}  {w['sha256'][:12]}…", flush=True)
        wheels.append(w)
    src_path = MANIFEST / "sources.json"
    src = json.loads(src_path.read_text()) if src_path.exists() else {"schema": 1}
    src["wheels"] = wheels
    src_path.write_text(json.dumps(src, indent=1) + "\n")
    lock = ["# Generated by scripts/pin_wheels.py from requirements.in. Do not edit.",
            "# utils3d is appended by build_payload after building it from its pinned commit."]
    for w in wheels:
        lock.append(f"{w['name']}=={w['version']} --hash=sha256:{w['sha256']}")
    (MANIFEST / "requirements.lock").write_text("\n".join(lock) + "\n")
    print(f"{len(wheels)} wheels pinned")


if __name__ == "__main__":
    sys.exit(main())
